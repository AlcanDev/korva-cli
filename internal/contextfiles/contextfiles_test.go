func at(s string) *time.Time {
	t, _ := time.Parse(time.RFC3339, s)
	return &t
}

func sampleData() Data {
	return Data{
		ServerURL: "https://platform.korva.dev",
		Project:   "atlas",
		Context: &api.ProjectContext{
			Project:  "atlas",
			HeadSHA:  strings.Repeat("a", 40),
			Branch:   "main",
			RepoURL:  "https://example.com/org/atlas",
			PushedAt: at("2026-08-20T10:00:00Z"),
			BriefMD:  "Atlas is the billing service. Go + Postgres.",
			BriefBy:  "lead@team.com",
			Branches: []api.ContextBranch{{Name: "main"}, {Name: "develop"}},
			Stale:    true,
		},
		Portfolio: []api.ProjectContext{
			{Project: "atlas", HeadSHA: strings.Repeat("a", 40), Branch: "main",
				PushedAt: at("2026-08-20T10:00:00Z"), BriefMD: "Atlas is the billing service.", Stale: true},
			{Project: "lyra"}, // registry-only: never pushed
		},
		Observations: []api.Observation{
			{ID: "01OBS", Kind: "decision", Title: "Use slog",
				Content: "Chose slog over zerolog.\nStdlib alignment."},
		},
		GeneratedAt: time.Date(2026, 8, 22, 12, 0, 0, 0, time.UTC),
	}
}

func TestRenderBrief(t *testing.T) {
	out := RenderBrief(sampleData())
	for _, want := range []string{
		"generated by korva context pull",
		"main@aaaaaaaaaaaa",
		"# atlas",
		"STALE",
		"Atlas is the billing service.",
		"_Curated by lead@team.com_",
		"Branches: main, develop",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("brief missing %q:\n%s", want, out)
		}
	}
}

func TestRenderBriefNoContext(t *testing.T) {
	d := sampleData()
	d.Context = nil
	out := RenderBrief(d)
	if !strings.Contains(out, "no context record yet") || !strings.Contains(out, "korva context push") {
		t.Errorf("missing wiring hint:\n%s", out)
	}
}

