func TestRenderDecisions(t *testing.T) {
	out := RenderDecisions(sampleData())
	for _, want := range []string{"`01OBS`", "[decision]", "Use slog", "vault_get", "Chose slog over zerolog. Stdlib alignment."} {
		if !strings.Contains(out, want) {
			t.Errorf("decisions missing %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, "\nStdlib") {
		t.Error("content snippet must be collapsed to one line")
	}
}

func TestWriteCreatesFiles(t *testing.T) {
	root := t.TempDir()
	written, err := Write(root, sampleData())
	if err != nil {
		t.Fatalf("Write: %v", err)
	}
	if len(written) != 3 {
		t.Fatalf("wrote %d files, want 3", len(written))
	}
	for _, rel := range written {
		if _, err := os.Stat(filepath.Join(root, rel)); err != nil {
			t.Errorf("missing %s: %v", rel, err)
		}
	}
}

func TestEnsureGitignore(t *testing.T) {
	root := t.TempDir()

	// No .gitignore yet → created with the line.
	changed, err := EnsureGitignore(root)
	if err != nil || !changed {
		t.Fatalf("first ensure: changed=%v err=%v", changed, err)
	}
	data, _ := os.ReadFile(filepath.Join(root, ".gitignore"))
	if !strings.Contains(string(data), ".korva/") {
		t.Fatalf(".gitignore missing entry: %q", data)
	}

	// Second call is a no-op.
	changed, err = EnsureGitignore(root)
	if err != nil || changed {
		t.Errorf("second ensure: changed=%v err=%v, want no-op", changed, err)
	}

	// Pre-existing content is preserved and appended to.
	root2 := t.TempDir()
	if err := os.WriteFile(filepath.Join(root2, ".gitignore"), []byte("node_modules/\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if changed, err = EnsureGitignore(root2); err != nil || !changed {
		t.Fatalf("append ensure: changed=%v err=%v", changed, err)
	}
	data, _ = os.ReadFile(filepath.Join(root2, ".gitignore"))
	if !strings.Contains(string(data), "node_modules/") || !strings.Contains(string(data), ".korva/") {
		t.Errorf("append lost content: %q", data)
	}
}
